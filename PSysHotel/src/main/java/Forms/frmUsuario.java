   public void Cadastro()
   {
       Usuario usuario = new Usuario();
       usuario.setCpf(txtCpf.getText().trim());
       usuario.setSenha(txtSenha.getText().trim());
        if (usuario.getCpf().isEmpty() || usuario.getSenha().isEmpty())
        {
            JOptionPane.showMessageDialog(this, "Preencha todos os campos");
            return;
        }
        try
        {
            ManutencaoSQL sql = new  ManutencaoSQL ();
            sql.cadastrarUsuario(usuario.getCpf(),usuario.getSenha());
             JOptionPane.showMessageDialog(this, "Usuário cadastrado");
        }
        catch (SQLException erro)
        {
             JOptionPane.showMessageDialog(this, "Erro no cadastro"+erro.getMessage());
        }
       
   }
       
    
       
